/**
 * Public-text boundary for private internal Slack ticket threads.
 *
 * The canonical record and full customer conversation stay in Bloom Support.
 * Only a short, redacted operational brief can be sent to Slack.
 */
import { redactForEngineering } from "./policy.ts";

export interface TicketFacts {
  id?: unknown; number?: unknown; subject?: unknown; summary?: unknown;
  account?: unknown; product?: unknown; priority?: unknown;
  status?: unknown; stage?: unknown; automation?: unknown;
  executor?: unknown; owner?: unknown; executor_person?: unknown;
  next_action?: unknown; resolution_summary?: unknown; resolution_verified?: unknown;
  jobs?: unknown; history?: unknown; updated_at?: unknown;
}
const UUID = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i;
const PHONE = /(?:\+?1[\s().-]*)?\(?[2-9]\d{2}\)?[\s().-]*[2-9]\d{2}[\s.-]*\d{4}\b/g;
const EMAIL = /[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi;
const URL = /(?:https?:\/\/|www\.)\S+/gi;
const AUTH = /\b(?:password|secret|api[-_ ]?key|access[_ -]?token|refresh[_ -]?token|private key|authorization|bearer|otp|pin|cvv)\b\s*(?:is|:|=)\s*\S+/i;
const CARD = /(?:\d[ -]?){13,19}/g;
const clean = (v: unknown): string => typeof v === "string" ? v : "";
const obj = (v: unknown): Record<string, unknown> =>
  v && typeof v === "object" && !Array.isArray(v) ? v as Record<string, unknown> : {};
const text = (v: unknown, max = 400): string => {
  const raw = clean(v).slice(0, 2000);
  if (!raw.trim()) return "";
  if (AUTH.test(raw) || /-----BEGIN [^-]+PRIVATE KEY-----/i.test(raw)) return "Sensitive details are in Bloom Support";
  const compact = raw.replace(/^(?:(?:from|to|cc|bcc|reply-to|subject|sent|date):.*(?:\r?\n|$))+/gim, " ")
    .replace(/(?:^|\n)\s*>[^\n]*(?=\n|$)/g, " ")
    .replace(/\b(?:https?:\/\/|www\.)\S+/gi, "[link in support desk]")
    .replace(CARD, (m) => m.replace(/\D/g,"").length>=13 ? "[payment information]" : m);
  const redacted = redactForEngineering(compact)
    .replace(EMAIL,"[email in support desk]")
    .replace(PHONE,"[phone in support desk]")
    .replace(URL,"[link in support desk]");
  // Slack formatting and mentions must never be generated by source text.
  return redacted.replace(/[<>@&*_`~|]/g," ").replace(/\p{Cc}/gu," ")
    .replace(/\s+/g," ").trim().slice(0,max);
};
export const safeTicketText = text;

const statusLabels: Record<string,string> = {
  new: "New", working: "Being handled", waiting: "Waiting",
  needs_owner: "Needs a decision", resolved: "Marked resolved",
};
const productLabels: Record<string,string> = {
  cms: "BloomSites", crm: "BloomSuite CRM", pos: "BloomSuite POS",
  platform: "Brands in Blooms platform", unknown: "Support",
};
const name = (v: unknown): string => text(obj(v).name,80);
const safeNumber = (v: unknown): number | null =>
  typeof v === "number" && Number.isSafeInteger(v) && v > 0 ? v : null;
export function supportTicketLink(id: unknown): string {
  const ticketId=clean(id);
  return UUID.test(ticketId) ?
    "https://bloomsuite.app/admin/bloom-support?view=queue&ticket="+ticketId :
    "https://bloomsuite.app/admin/bloom-support";
}
export function ticketNumber(v: unknown): number | null { return safeNumber(v); }
export function ticketStatus(t: TicketFacts): string {
  const s=clean(t.status);
  if(s==="resolved" && t.resolution_verified===true) return "Verified resolved";
  return statusLabels[s] ?? "Status not recorded";
}
export function ticketOwnership(t: TicketFacts): string {
  const owner=name(t.owner);
  if(owner) return owner;
  const person=name(t.executor_person);
  if(clean(t.executor)==="person") return person || "A support person (name not recorded)";
  if(clean(t.automation)==="auto" && clean(t.executor)==="bloom") return "Bloom (automated review)";
  return "Not assigned to a support person";
}
export function ticketBloomStatus(t: TicketFacts): string {
  if(clean(t.status)==="resolved") return t.resolution_verified===true ?
    "The record is marked verified resolved. The customer result should still match the recorded evidence." :
    "The record was marked resolved, but no verified customer result is recorded.";
  if(clean(t.executor)==="person")
    return "A support person is handling this. Bloom will not take over their work.";
  if(clean(t.automation)!=="auto")
    return "Automatic work is paused. A support person needs to review the next step.";
  const jobs=Array.isArray(t.jobs) ? t.jobs.map(obj) : [];
  const active=jobs.find(j=>["running","leased","processing"].includes(clean(j.status)));
  if(active) return "Bloom has an active job recorded in the support queue.";
  const queued=jobs.find(j=>["queued","pending","retry"].includes(clean(j.status)));
  if(queued) return "Bloom has a task queued for processing. Completion is not yet confirmed.";
  return "Bloom is assigned for initial review, but there is no active job confirmed right now.";
}
export function ticketNextAction(t: TicketFacts): string {
  const n=text(t.next_action,240);
  if(n) return n;
  if(clean(t.status)==="resolved") return "Check the recorded resolution against the customer's original problem.";
  if(clean(t.status)==="needs_owner") return "An authorized administrator needs to make the next decision.";
  if(clean(t.status)==="waiting") return "Review what the team is waiting for before continuing.";
  if(clean(t.executor)==="person") return "The support owner should record the next action.";
  if(clean(t.automation)==="auto") return "Bloom is handling the initial review; check its recorded progress.";
  return "Assign a support person and decide what should happen next.";
}
export function ticketProblem(t: TicketFacts): string {
  const body=text(t.summary,440);
  const subject=text(t.subject,130);
  // The summary is normally the description. Forwarded emails may have a
  // long header; never quote the complete raw message or attachments.
  return body || subject || "The full description is available in Bloom Support.";
}
export function ticketRootMessage(t: TicketFacts, eventKind = "ticket.created"): string {
  const n=safeNumber(t.number);
  if(!n || !UUID.test(clean(t.id))) throw new Error("invalid ticket for Slack");
  const account=name(t.account);
  const category=productLabels[clean(t.product)] ?? productLabels.unknown;
  const title = eventKind==="ticket.created" ? "New support ticket" : "Support ticket";
  const priority=clean(t.priority);
  return [
    "*"+title+" #"+n+"*",
    "*Client:* "+(account || "Client not linked")+" · *Product:* "+category+
      (["high","urgent"].includes(priority) ? " · *Priority:* "+priority : ""),
    "*Problem:* "+ticketProblem(t),
    "*Status:* "+ticketStatus(t),
    "*Who is handling it:* "+ticketOwnership(t),
    "*What Bloom is doing:* "+ticketBloomStatus(t),
    "*Next step:* "+ticketNextAction(t),
    "_Reply in this thread with @Bloom to ask about this ticket. Open the dashboard only to edit, approve or view sensitive details._",
    "<"+supportTicketLink(t.id)+"|Open ticket and actions>",
  ].join("\n");
}
export function ticketUpdateMessage(t: TicketFacts, eventKind: string): string {
  const n=safeNumber(t.number);
  if(!n || !UUID.test(clean(t.id))) throw new Error("invalid ticket for Slack");
  const who=ticketOwnership(t);
  const headline=clean(t.executor)==="person" && who!=="Not assigned to a support person" ?
    "Support handoff / progress" : "Support progress";
  return [
    "*"+headline+" · Ticket #"+n+"*",
    "*Status:* "+ticketStatus(t),
    "*Handling it:* "+who,
    "*What Bloom is doing:* "+ticketBloomStatus(t),
    "*Next step:* "+ticketNextAction(t),
    eventKind==="engineering.verified" ?
      "*Verification:* Engineering reported verification. Confirm the affected customer workflow in the linked record." : "",
    "_Ask @Bloom in this thread for the current status, recorded problem or next action._",
    "<"+supportTicketLink(t.id)+"|Open ticket actions>",
  ].filter(Boolean).join("\n");
}
export function ticketQuestionAnswer(t: TicketFacts, question: unknown): string {
  const q=clean(question).slice(0,800);
  const n=safeNumber(t.number);
  if(!n || !UUID.test(clean(t.id))) return "That ticket could not be verified.";
  const intro="*Ticket #"+n+"* · "+ticketStatus(t);
  const change=/\b(fix|repair|deploy|publish|refund|send|approve|delete|change|take over|take this|assign me)\b/i.test(q);
  if(change) return [
    intro,
    "I can explain the recorded problem and prepare a safe handoff, but a Slack message cannot approve a repair, change ownership, publish code, issue a refund or contact the customer.",
    "*Current owner:* "+ticketOwnership(t),
    "*Next step:* "+ticketNextAction(t),
    "<"+supportTicketLink(t.id)+"|Review the authorized actions>",
  ].join("\n");
  if(/\b(who|owner|assigned|handling|taking|responsible)\b/i.test(q)) return [
    intro,"*Handling it:* "+ticketOwnership(t),
    "*Bloom:* "+ticketBloomStatus(t),
    "*Next step:* "+ticketNextAction(t),
  ].join("\n");
  if(/\b(what happened|what is wrong|problem|description|why|cause|issue)\b/i.test(q)) return [
    intro,"*Recorded problem:* "+ticketProblem(t),
    "*Known cause:* A cause is not verified unless the support record confirms it.",
    "*What we're doing:* "+ticketBloomStatus(t),
    "*Next step:* "+ticketNextAction(t),
  ].join("\n");
  if(/\b(next|blocked|waiting|priority|action|to do|should we do)\b/i.test(q)) return [
    intro,"*Owner:* "+ticketOwnership(t),
    "*Next step:* "+ticketNextAction(t),
    "*Bloom:* "+ticketBloomStatus(t),
  ].join("\n");
  if(/\b(verified|resolved|done|finished|working|live|test|result|evidence)\b/i.test(q)) return [
    intro,"*Verification:* "+(t.resolution_verified===true?"Recorded as verified.":"A passing customer-workflow verification is not recorded."),
    "*What Bloom is doing:* "+ticketBloomStatus(t),
    "*Next step:* "+ticketNextAction(t),
  ].join("\n");
  return [
    intro,
    "*Problem:* "+ticketProblem(t),
    "*Owner:* "+ticketOwnership(t),
    "*What Bloom is doing:* "+ticketBloomStatus(t),
    "*Next step:* "+ticketNextAction(t),
    "_You can ask me what's wrong, who's handling it, what changed, whether it was verified, or what's next. I won't make changes without the proper authorization._",
  ].join("\n");
}
